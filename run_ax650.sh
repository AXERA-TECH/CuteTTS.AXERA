#!/bin/bash
# CuteTTS.AXERA one-click demo (voice cloning on AX650).
#   bash run_ax650.sh "text" [reference.wav] [output.wav] [--python] [--cfg 2.0] [--seed 42] [--max-new N]
set -e
cd "$(dirname "$0")"
export LD_LIBRARY_PATH=/soc/lib:${LD_LIBRARY_PATH:-}
export PYTHONDONTWRITEBYTECODE=1

TEXT="${1:-The voice generated by this model sounds amazing!}"
REF="${2:-samples/reference.wav}"
OUT="${3:-output.wav}"
if [ $# -ge 3 ]; then shift 3; elif [ $# -ge 2 ]; then shift 2; elif [ $# -ge 1 ]; then shift 1; fi

MODE="cpp"
EXTRA=()
for a in "$@"; do
  case "$a" in
    --python) MODE="python" ;;
    --cpp) MODE="cpp" ;;
    *) EXTRA+=("$a") ;;
  esac
done
if [ ! -x ./bin/cutetts_ax650 ]; then MODE="python"; fi

if [ "$MODE" = "cpp" ]; then
  exec ./bin/cutetts_ax650 --model-dir models --assets models/assets \
      --text "$TEXT" --reference "$REF" --output "$OUT" "${EXTRA[@]}"
else
  exec python3 python/demo.py --model-dir models --assets models/assets \
      --text "$TEXT" --reference "$REF" --output "$OUT" "${EXTRA[@]}"
fi
