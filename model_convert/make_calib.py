def load24(path, maxsec=20.0):
    wav, sr = sf.read(path, dtype="float32", always_2d=True)
    wav = wav.mean(axis=1)
    if sr != 24000:
        g = np.gcd(int(sr), 24000)
        wav = resample_poly(wav, 24000 // g, int(sr) // g)
    n = int(maxsec * 24000)
    return torch.from_numpy(np.ascontiguousarray(wav[:n], dtype=np.float32))[None, None]


def load16(path, maxsec=8.0):
    wav, sr = sf.read(path, dtype="float32", always_2d=True)
    wav = wav.mean(axis=1)
    if sr != 16000:
        g = np.gcd(int(sr), 16000)
        wav = resample_poly(wav, 16000 // g, int(sr) // g)
    n = int(maxsec * 16000)
    w = wav[:n]
    if len(w) < 32000:
        w = np.tile(w, int(np.ceil(32000 / len(w))))
        w = w[:n if len(w) > n else len(w)]
    return torch.from_numpy(np.ascontiguousarray(w, dtype=np.float32))[None]


def save(model, name, arr, tag):
    d = os.path.join(CALIB, model, name)
    os.makedirs(d, exist_ok=True)
    np.save(os.path.join(d, f"{tag}.npy"), np.asarray(arr, dtype=np.float32))


def main():
    cfg, model, vae, spk = E.load_all()
    E.dh.F.scaled_dot_product_attention = M.manual_sdpa
    proc = CuteTTSProcessor(
        acoustic_vae_path=os.path.join(E.ORIGIN, "weights", "audio_vae"),
        tokenizer=os.path.join(E.ORIGIN, "tokenizer"),
        segment_cfg=SegmentManagerConfig(**cfg["processor"]["segment"]),
        speech_compress_rate=1920, feature_extractor_internal_batchsize=None,
        feature_extractor_sort_batches=True, sequence_style="auto_reference",
        enable_condition_drop=False, text_suffix_token="<|endofprompt|>",
        acoustic_feature_no_sampling=True, packing_enabled=False,
        speaker_embedding_enabled=True, speaker_embedding_source="precomputed",
        speaker_embedding_dim=256, lm_speaker_linear_enabled=True,
        text_only_prompt_style="instruction", reset_previous_cond_at_target_start=True,
        self_reference_mode="combined",
    ).float().eval()

    enc = M.VAEEncoder(vae)
    spk_mel = spk.feature_extract
    scaler = float(model.speech_scaling_factor)
    bias = float(model.speech_bias_factor)

    latents = []
    lat_all = {}
    for i, path in enumerate(WAVS):
        if not os.path.exists(path):
            print("skip", path)
            continue
        try:
            wav24 = load24(path)
        except Exception as exc:
            print("skip", path, exc)
            continue
        tag = f"u{i:02d}"
        p = torch.nn.functional.pad(wav24, (0, M.VAE_ENC_T - wav24.shape[-1]))
        with torch.no_grad():
            lat = enc(p)  # [1,L,64]
        latents.append((tag, lat))
        lat_all[tag] = lat
        save("vae_enc", "wav", p.numpy(), tag)
        # speaker logmel (board computes logmel in numpy; calibration uses torch's)
        wav16 = load16(path)
        with torch.no_grad():
            mel = spk_mel(wav16)[0][None]
        mel = torch.nn.functional.pad(mel, (0, M.SPK_T - mel.shape[-1]))
        save("speaker_enc", "logmel", mel.numpy(), tag)
        print("vae/spk", tag, lat.shape, mel.shape)

    # locenc calibration
    for tag, lat in latents:
        x = lat[0]
        if x.shape[0] % 2:
            x = torch.cat([x, torch.zeros(1, 64)], 0)
        patches = x.reshape(1, -1, 2, 64)
        pb = torch.zeros(1, M.LOCENC_PROMPT_N, 2, 64)
        pb[:, : min(patches.shape[1], M.LOCENC_PROMPT_N)] = patches[:, : M.LOCENC_PROMPT_N]
        save("locenc_prompt", "patches", pb.numpy(), tag)
        for k in range(3):
            if k < patches.shape[1]:
                save("locenc_step", "patches", patches[:, k : k + 1].numpy(), f"{tag}_{k}")

    # prompt / lm calibration
    pipe = R.RefPipe(cfg, model, vae, spk)
    n_prefill, n_dec = 0, 0
    for i, text in enumerate(TEXTS):
        path = WAVS[i % len(WAVS)]
        wav24 = load24(path, maxsec=12.0)
        mode_clone = True
        embeds, dit_spk, ref_lat = R.build_prompt(model, proc, spk, wav24, text, mode_clone)
        L = embeds.shape[1]
        if L > M.TP:
            print("prompt too long, truncate reference", L)
            wav24 = load24(path, maxsec=6.0)
            embeds, dit_spk, ref_lat = R.build_prompt(model, proc, spk, wav24, text, True)
            L = embeds.shape[1]
        e = torch.zeros(1, M.TP, 1024)
        e[:, :L] = embeds
        save("lm_prefill", "embeds", e.numpy(), f"t{i:02d}")
        n_prefill += 1
        if i < 3:
            _, _, _, _, _ = pipe.run(embeds, dit_spk, max_new=24, calib_dir=CALIB, tag=f"t{i:02d}")
            n_dec += 1
        print("prompt", i, "len", L, "clone", mode_clone)

    # vae decoder calibration from real + generated latents
    gen = []
    for f in sorted(glob.glob(f"{CALIB}/dit/out_*.npy")):
        gen.append(torch.from_numpy(np.load(f)))
    idx = 0
    for tag, lat in latents:
        x = (lat[0] / scaler - bias).T  # [64,L]
        n = x.shape[-1]
        for lb in (64, 128, 256):
            if n <= lb:
                p = torch.zeros(1, 64, lb)
                p[:, :, :n] = x
                save(f"vae_dec_l{lb}", "latent", p.numpy(), tag)
    for g in gen:
        z = (g / scaler - bias)  # [1,2,64]
        x = z.reshape(1, -1, 64).transpose(1, 2)  # [1,64,2]
        for lb in (64, 128, 256):
            p = torch.zeros(1, 64, lb)
            p[:, :, :2] = x
            save(f"vae_dec_l{lb}", "latent", p.numpy(), f"g{idx:02d}")
        idx += 1
    print("done: prefill", n_prefill, "dec utts", n_dec)
    for d in sorted(glob.glob(f"{CALIB}/*")):
        files = glob.glob(f"{d}/*/*.npy")
        if files:
            print(os.path.basename(d), len(files))


if __name__ == "__main__":
    main()
