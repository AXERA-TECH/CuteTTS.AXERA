#include <cmath>
#include <cstdio>
#include <cstring>
#include <random>
#include <sys/stat.h>
#include <sys/types.h>
#include <functional>
#include <string>
#include <vector>

#include "audio.hpp"
#include "ax_runner.hpp"
#include "text_split.hpp"
#include "tokenizer.hpp"

namespace {

constexpr int SR = 24000;
constexpr int HOP = 1920;
constexpr int LATENT = 64;
constexpr int PATCH = 2;
constexpr int TP = 256;
constexpr int KV = 384;
constexpr int HID = 1024;
constexpr int VAE_ENC_N = 120000;
constexpr int SPK_N = 800;
constexpr int SPK_STATS = 6912;

const char* kPrefix =
    "Transform the text into speech output, utilizing the distinct voice of the provided "
    "speech sample.\nvoice reference:\n<|im_start|>";
const char* kMid = "<|im_end|>\n<|im_start|>";
const char* kSuffixFmt = "<|im_end|>\ntext input:\n%s\n<|endofprompt|>";

struct Assets {
    std::vector<float> embed;      // [16385][1024] fp16 -> f32
    std::vector<float> spk_proj;   // [1024][256]
    std::vector<float> mel_fb;     // [80][257]
    std::vector<float> mel_win;    // [400]
    std::vector<float> bn_mean, bn_var, bn_w, bn_b, lin_w, lin_b;
    float scale = 0.4127216339111328f;
    float bias = -0.0021514892578125f;
};

static bool load_assets(const std::string& dir, Assets& a) {
    cutetts::Npy npy;
    auto path = [&](const char* n) { return dir + "/" + n; };
    if (!cutetts::read_npy(path("embed_tokens.npy"), npy)) return false;
    a.embed.swap(npy.data);
    if (!cutetts::read_npy(path("lm_speaker_proj.npy"), npy)) return false;
    a.spk_proj.swap(npy.data);
    if (!cutetts::read_npy(path("mel_filter.npy"), npy)) return false;
    a.mel_fb.swap(npy.data);
    if (!cutetts::read_npy(path("mel_window.npy"), npy)) return false;
    a.mel_win.swap(npy.data);
    const char* names[] = {"spk_bn_mean.npy", "spk_bn_var.npy", "spk_bn_w.npy", "spk_bn_b.npy",
                           "spk_linear_w.npy", "spk_linear_b.npy"};
    std::vector<float>* dst[] = {&a.bn_mean, &a.bn_var, &a.bn_w, &a.bn_b, &a.lin_w, &a.lin_b};
    for (int i = 0; i < 6; ++i) {
        if (!cutetts::read_npy(path(names[i]), npy)) return false;
        dst[i]->swap(npy.data);
    }
    // config.json (scaling / bias)
    FILE* f = std::fopen(path("config.json").c_str(), "rb");
    if (f) {
        std::string s;
        char buf[4096];
        size_t n = std::fread(buf, 1, sizeof(buf) - 1, f);
        buf[n] = 0;
        s = buf;
        std::fclose(f);
        auto getf = [&](const char* key, float& out) {
            size_t p = s.find(key);
            if (p == std::string::npos) return;
            p = s.find(':', p);
            if (p == std::string::npos) return;
            out = std::strtof(s.c_str() + p + 1, nullptr);
        };
        getf("\"speech_scaling_factor\"", a.scale);
        getf("\"speech_bias_factor\"", a.bias);
    }
    return true;
}

static void run_rope(int pos, std::vector<float>& cos_t, std::vector<float>& sin_t) {
    cos_t.assign(128, 0.f);
    sin_t.assign(128, 0.f);
    for (int i = 0; i < 64; ++i) {
        const float inv = 1.0f / std::pow(1e6f, (2.0f * i) / 128.0f);
        const float freq = static_cast<float>(pos) * inv;
        const float c = std::cos(freq), s = std::sin(freq);
        cos_t[i] = cos_t[i + 64] = c;
        sin_t[i] = sin_t[i + 64] = s;
    }
}

struct Models {
    cutetts::AxModel vae_enc, spk_body, loc, prefill, dec, dit, dec128, dec256;
};

}  // namespace

int main(int argc, char** argv) {
    std::string model_dir = "models";
    std::string assets_dir = "models/assets";
    std::string text = "The voice generated by this model sounds amazing!";
    std::string ref_path = "samples/reference.wav";
    std::string out_path = "output.wav";
    float cfg_strength = 2.0f;
    int max_new = KV - TP - 1;
    int seed = 42;
    bool debug_ids = false;
    bool stream = false;
    bool stateful_mode = false;
    std::string ref_cache_dir = "cache/ref";
    int first_chunk = 4;
    int chunk = 16;
    bool split = false;                 // --split: 长文本按句切分，逐句生成
    double split_sec = 18.0;            // --split-sec: 每段目标时长上限（秒）
    for (int i = 1; i < argc; ++i) {
        const char* a = argv[i];
        auto next = [&]() { return std::string(i + 1 < argc ? argv[++i] : ""); };
        if (!std::strcmp(a, "--model-dir")) model_dir = next();
        else if (!std::strcmp(a, "--assets")) assets_dir = next();
        else if (!std::strcmp(a, "--text")) text = next();
        else if (!std::strcmp(a, "--reference")) ref_path = next();
        else if (!std::strcmp(a, "--output")) out_path = next();
        else if (!std::strcmp(a, "--cfg")) cfg_strength = std::strtof(next().c_str(), nullptr);
        else if (!std::strcmp(a, "--max-new")) max_new = std::atoi(next().c_str());
        else if (!std::strcmp(a, "--seed")) seed = std::atoi(next().c_str());
        else if (!std::strcmp(a, "--debug-ids")) debug_ids = true;
        else if (!std::strcmp(a, "--stream")) stream = true;
        else if (!std::strcmp(a, "--stateful")) stateful_mode = true;
        else if (!std::strcmp(a, "--ref-cache")) ref_cache_dir = next();
        else if (!std::strcmp(a, "--first-chunk")) first_chunk = std::atoi(next().c_str());
        else if (!std::strcmp(a, "--chunk")) chunk = std::atoi(next().c_str());
        else if (!std::strcmp(a, "--split")) split = true;
        else if (!std::strcmp(a, "--split-sec")) split_sec = std::atof(next().c_str());
        else {
            std::fprintf(stderr, "unknown arg %s\n", a);
            return 1;
        }
    }

    Assets A;
    if (!load_assets(assets_dir, A)) {
        std::fprintf(stderr, "failed to load assets from %s\n", assets_dir.c_str());
        return 2;
    }
    cutetts::Tokenizer tok;
    if (!tok.load(assets_dir + "/tokenizer.bin")) return 2;

    Models M;
    auto mpath = [&](const char* n) { return model_dir + "/" + n + ".axmodel"; };
    if (!M.vae_enc.load(mpath("vae_enc")) || !M.spk_body.load(mpath("spk_body")) ||
        !M.loc.load(mpath("locenc_step")) || !M.prefill.load(mpath("lm_prefill")) ||
        !M.dec.load(mpath("lm_decode")) || !M.dit.load(mpath("dit_step")) ||
        !M.dec128.load(mpath("vae_dec_l128")) ||
        !M.dec256.load(mpath("vae_dec_l256"))) {
        std::fprintf(stderr, "failed to load axmodels from %s\n", model_dir.c_str());
        return 3;
    }

    // optional stateful streaming decoder
    cutetts::AxModel dec_stream;
    bool has_stream_dec = stateful_mode && dec_stream.load(mpath("vae_dec_stream"));
    // exact sliding-window decoder (prefer the dedicated 80-latent graph)
    cutetts::AxModel dec_win;
    int win_len = 128;
    if (dec_win.load(mpath("vae_dec_l80"))) win_len = 80;
    std::vector<std::vector<int>> state_shapes;
    if (has_stream_dec) {
        FILE* jf = std::fopen((assets_dir + "/vae_stream.json").c_str(), "rb");
        if (jf) {
            std::string txt;
            char buf[4096];
            size_t n = std::fread(buf, 1, sizeof(buf) - 1, jf);
            buf[n] = 0;
            txt = buf;
            std::fclose(jf);
            std::vector<int> nums;
            for (size_t i = 0; i < txt.size(); ++i) {
                if (std::isdigit((unsigned char)txt[i])) {
                    int v = 0;
                    while (i < txt.size() && std::isdigit((unsigned char)txt[i])) v = v * 10 + (txt[i++] - '0');
                    nums.push_back(v);
                }
            }
            for (size_t i = 0; i + 2 < nums.size(); i += 3)
                state_shapes.push_back({nums[i], nums[i + 1], nums[i + 2]});
        }
        if (state_shapes.empty()) has_stream_dec = false;
    }

    // warm up every graph so the first request does not pay NPU lazy-init cost
    {
        cutetts::AxModel* warm[] = {&M.vae_enc, &M.spk_body, &M.loc, &M.prefill, &M.dec, &M.dit,
                                    &M.dec128, &M.dec256};
        for (auto* m : warm) m->warmup();
        if (win_len == 80) dec_win.warmup();
        if (has_stream_dec) dec_stream.warmup();
    }

    const auto t_start = std::chrono::steady_clock::now();
    int emitted_ = 0;
    auto now = []() { return std::chrono::steady_clock::now(); };
    auto ms = [](auto a, auto b) {
        return std::chrono::duration<double, std::milli>(b - a).count();
    };

    // ---------------------------------------------------------------- reference
    std::vector<float> wav;
    int sr = 0;
    if (!cutetts::read_wav(ref_path, wav, sr)) return 4;
    std::vector<float> wav24 = cutetts::resample_to(wav, sr, SR);
    if (wav24.size() > (size_t)VAE_ENC_N) wav24.resize(VAE_ENC_N);
    const int nreal = static_cast<int>(wav24.size() / HOP);
    wav24.resize(VAE_ENC_N, 0.f);
    // ---- reference feature cache (skips vae_enc + speaker on repeat voices) ----
    int n_lat = 0;
    std::vector<float> latent;
    std::vector<float> spk(256, 0.f);
    std::string cache_file;
    bool ref_cached = false;
    {
        struct stat stt;
        if (stat(ref_path.c_str(), &stt) == 0) {
            char key[256];
            std::snprintf(key, sizeof(key), "%s_%lld_%lld.ref", ref_path.c_str(),
                          (long long)stt.st_size, (long long)stt.st_mtime);
            cache_file = ref_cache_dir + "/" + std::to_string(std::hash<std::string>{}(key)) + ".ref";
        }
    }
    if (!cache_file.empty()) {
        FILE* cf = std::fopen(cache_file.c_str(), "rb");
        if (cf) {
            int nl = 0;
            if (std::fread(&nl, 4, 1, cf) == 1 && nl > 0 && nl <= 62) {
                std::vector<float> lat((size_t)nl * LATENT);
                if (std::fread(lat.data(), 4, lat.size(), cf) == lat.size() &&
                    std::fread(spk.data(), 4, 256, cf) == 256) {
                    latent.swap(lat);
                    n_lat = nl;
                    ref_cached = true;
                }
            }
            std::fclose(cf);
        }
    }
    auto t0 = now();
    if (!ref_cached) {
        std::vector<float> in(VAE_ENC_N, 0.f);
        std::memcpy(in.data(), wav24.data(), VAE_ENC_N * sizeof(float));
        if (!M.vae_enc.set("wav", in) || !M.vae_enc.run()) return 5;
        latent = M.vae_enc.get("latent", 62 * LATENT);
        if (latent.empty()) return 5;
        n_lat = std::max(1, std::min(nreal, 62));
        latent.resize((size_t)n_lat * LATENT);
    }
    auto t1 = now();

    // speaker: 16 kHz log-mel -> ECAPA body -> host BN+linear+L2
    auto tp0 = now();
    std::vector<float> w16 = ref_cached ? std::vector<float>()
                                    : cutetts::resample_to(wav, sr, 16000);
    auto tp1 = now();
    if (!ref_cached && w16.size() > 8 * 16000) w16.resize(8 * 16000);
    if (!ref_cached && w16.size() < 32000) {
        const size_t rep = (32000 + w16.size() - 1) / w16.size();
        std::vector<float> tmp;
        tmp.reserve(w16.size() * rep);
        for (size_t i = 0; i < rep; ++i) tmp.insert(tmp.end(), w16.begin(), w16.end());
        w16.swap(tmp);
    }
    std::vector<float> mel = ref_cached ? std::vector<float>()
                                        : cutetts::logmel(w16, A.mel_fb, A.mel_win);
    auto tp2 = now();
    auto tp3 = tp2, tp4 = tp2;
    const int frames = static_cast<int>(mel.size() / 80);
    std::vector<float> mel_pad((size_t)80 * SPK_N, 0.f);
    if (!ref_cached) {
        const int use_f = std::min(frames, SPK_N);
        for (int m = 0; m < 80; ++m)
            std::memcpy(&mel_pad[(size_t)m * SPK_N], &mel[(size_t)m * frames], use_f * sizeof(float));
        if (!M.spk_body.set("logmel", mel_pad) || !M.spk_body.run()) return 6;
        tp3 = now();
        std::vector<float> stats = M.spk_body.get("stats", SPK_STATS);
        std::vector<float> y(SPK_STATS);
        for (int i = 0; i < SPK_STATS; ++i)
            y[i] = (stats[i] - A.bn_mean[i]) / std::sqrt(A.bn_var[i] + 1e-5f) * A.bn_w[i] + A.bn_b[i];
        double norm = 0;
        for (int o = 0; o < 256; ++o) {
            double acc = 0;
            const float* row = &A.lin_w[(size_t)o * SPK_STATS];
            for (int i = 0; i < SPK_STATS; ++i) acc += row[i] * y[i];
            spk[o] = static_cast<float>(acc + A.lin_b[o]);
            norm += double(spk[o]) * spk[o];
        }
        norm = std::sqrt(norm) + 1e-12;
        for (auto& v : spk) v = static_cast<float>(v / norm);
        tp4 = now();
    }
    // 参考特征落盘推迟到首个音频发出之后：NFS 写一次约 200 ms，不能压在 TTFT/TTFA 上
    bool ref_cache_pending = !ref_cached && !cache_file.empty();
    double t_cache_flush = 0.0;
    auto flush_ref_cache = [&]() {
        if (!ref_cache_pending) return;
        ref_cache_pending = false;
        auto tf0 = now();
        std::string dir = ref_cache_dir;
        for (size_t i = 0; i < dir.size(); ++i)
            if (dir[i] == '/') { std::string sub = dir.substr(0, i); mkdir(sub.c_str(), 0755); }
        mkdir(dir.c_str(), 0755);
        if (FILE* cf = std::fopen(cache_file.c_str(), "wb")) {
            std::fwrite(&n_lat, 4, 1, cf);
            std::fwrite(latent.data(), 4, (size_t)n_lat * LATENT, cf);
            std::fwrite(spk.data(), 4, 256, cf);
            std::fclose(cf);
        }
        t_cache_flush = ms(tf0, now());
    };
    auto tp5 = now();
    if (std::getenv("CUTETTS_PROFILE"))
        std::fprintf(stderr, "    [host] resample %.0f ms  logmel %.0f ms  spk_npu %.0f ms  bn/lin %.0f ms\n",
                     ms(tp0, tp1), ms(tp1, tp2), ms(tp2, tp3), ms(tp3, tp4));
    auto t2 = now();

    // ---- 长文本按句切分：每段一次完整请求，音频顺序拼接 ----
    std::vector<std::string> segments =
        split ? cutetts::split_text(text, split_sec) : std::vector<std::string>{text};
    if (segments.empty()) segments.push_back(text);
    if (segments.size() > 1) {
        std::fprintf(stderr, "[split] %zu segments:", segments.size());
        for (const auto& sg : segments)
            std::fprintf(stderr, " %.1fs", cutetts::estimate_seconds(sg));
        std::fprintf(stderr, "\n");
    }
    cutetts::WavWriter writer;
    std::vector<float> offline_pcm;          // 非流式：所有分段拼接后的 PCM
    double t_dit_sum = 0.0, t_dec_sum = 0.0;
    double ttft = -1.0, t_first_lat = -1.0;
    auto t3 = now(), t4 = now(), t5 = now();
    int steps_sum = 0, chunks_sum = 0, total_lat_sum = 0;
    if (stream) {
        if (!writer.open(out_path, SR)) return 15;
    }
    for (size_t seg_i = 0; seg_i < segments.size(); ++seg_i) {
    const std::string& seg_text = segments[seg_i];

    // ------------------------------------------------------------------- prompt
    std::vector<int> ids_pre = tok.encode(kPrefix);
    std::vector<int> ids_mid = tok.encode(kMid);
    char sfx[2048];
    std::snprintf(sfx, sizeof(sfx), kSuffixFmt, seg_text.c_str());
    std::vector<int> ids_suf = tok.encode(sfx);

    if (debug_ids) {
        auto dump = [&](const char* tag, const std::vector<int>& v) {
            std::printf("%s (%zu):", tag, v.size());
            for (int x : v) std::printf(" %d", x);
            std::printf("\n");
        };
        dump("prefix", ids_pre);
        dump("mid", ids_mid);
        dump("suffix", ids_suf);
        return 0;
    }
    const int n_patch = (n_lat + PATCH - 1) / PATCH;
    const int n = static_cast<int>(ids_pre.size()) + 1 + (int)ids_mid.size() + n_patch + (int)ids_suf.size();
    if (n > TP) {
        std::fprintf(stderr, "prompt too long (%d > %d), use a shorter reference/text\n", n, TP);
        return 7;
    }
    std::vector<float> embeds((size_t)TP * HID, 0.f);
    auto put_row = [&](int row, const int* ids, int count) {
        for (int i = 0; i < count; ++i)
            std::memcpy(&embeds[(size_t)(row + i) * HID], &A.embed[(size_t)ids[i] * HID],
                        HID * sizeof(float));
    };
    put_row(0, ids_pre.data(), (int)ids_pre.size());
    const int spk_pos = (int)ids_pre.size();
    {
        std::vector<float> lmk(HID, 0.f);
        for (int o = 0; o < HID; ++o) {
            double acc = 0;
            const float* row = &A.spk_proj[(size_t)o * 256];
            for (int i = 0; i < 256; ++i) acc += row[i] * spk[i];
            lmk[o] = static_cast<float>(acc);
        }
        std::memcpy(&embeds[(size_t)spk_pos * HID], lmk.data(), HID * sizeof(float));
    }
    put_row(spk_pos + 1, ids_mid.data(), (int)ids_mid.size());
    const int speech_pos = spk_pos + 1 + (int)ids_mid.size();
    for (int p = 0; p < n_patch; ++p) {
        std::vector<float> patch((size_t)PATCH * LATENT, 0.f);
        for (int q = 0; q < PATCH; ++q) {
            const int idx = p * PATCH + q;
            if (idx >= n_lat) continue;
            for (int c = 0; c < LATENT; ++c) {
                const float v = latent[(size_t)idx * LATENT + c];
                patch[(size_t)q * LATENT + c] = (v + A.bias) * A.scale;
            }
        }
        if (!M.loc.set("patches", patch) || !M.loc.run()) return 8;
        std::vector<float> e = M.loc.get("embeds", HID);
        if (e.empty()) return 8;
        std::memcpy(&embeds[(size_t)(speech_pos + p) * HID], e.data(), HID * sizeof(float));
    }
    put_row(speech_pos + n_patch, ids_suf.data(), (int)ids_suf.size());
    t3 = now();

    // ------------------------------------------------------------------ prefill
    if (!M.prefill.set("embeds", embeds) || !M.prefill.run()) return 9;
    std::vector<float> hidden_all = M.prefill.get("hidden", (size_t)TP * HID);
    std::vector<float> stop = M.prefill.get("stop", 2);
    std::vector<std::vector<float>> kv(14);
    for (int i = 0; i < 7; ++i) {
        auto k = M.prefill.get("k" + std::to_string(i), (size_t)8 * TP * 128);
        auto v = M.prefill.get("v" + std::to_string(i), (size_t)8 * TP * 128);
        kv[2 * i].assign((size_t)8 * KV * 128, 0.f);
        kv[2 * i + 1].assign((size_t)8 * KV * 128, 0.f);
        for (int h = 0; h < 8; ++h) {
            std::memcpy(&kv[2 * i][(size_t)h * KV * 128], &k[(size_t)h * TP * 128],
                        (size_t)n * 128 * sizeof(float));
            std::memcpy(&kv[2 * i + 1][(size_t)h * KV * 128], &v[(size_t)h * TP * 128],
                        (size_t)n * 128 * sizeof(float));
        }
    }
    std::vector<float> hidden(HID, 0.f);
    std::memcpy(hidden.data(), &hidden_all[(size_t)(n - 1) * HID], HID * sizeof(float));
    t4 = now();

    // -------------------------------------------------------------- AR loop
    std::vector<float> mask((size_t)(KV + 1), -30.f);
    for (int i = 0; i < n; ++i) mask[i] = 0.f;
    mask[KV] = 0.f;
    std::vector<float> cond((size_t)PATCH * LATENT, 0.f);
    std::mt19937 gen(static_cast<uint32_t>(seed));
    std::normal_distribution<float> nd(0.f, 1.f);
    std::vector<float> lat_all;              // VAE-space latents, LATENT floats each
    double t_dit = 0, t_dec = 0;
    int pos = n, steps = 0, chunks = 0;
    emitted_ = 0;
    std::vector<float> streamed;             // 本段非流式 PCM

    auto decode_window = [&](int start, int end, std::vector<float>& out) {
        const int L = win_len;
        const int w0 = std::max(0, end - L);
        std::vector<float> win((size_t)LATENT * L, 0.f);
        for (int i = w0; i < end; ++i)
            for (int c = 0; c < LATENT; ++c)
                win[(size_t)c * L + (i - w0)] = lat_all[(size_t)i * LATENT + c];
        cutetts::AxModel& dm = (L == 80) ? dec_win : M.dec128;
        if (!dm.set("latent", win) || !dm.run()) return false;
        std::vector<float> wav = dm.get("wav", (size_t)L * HOP);
        if (wav.empty()) return false;
        out.assign(wav.begin() + (size_t)(start - w0) * HOP,
                   wav.begin() + (size_t)(end - w0) * HOP);
        return true;
    };
    std::vector<std::vector<float>> stream_states;
    if (has_stream_dec)
        stream_states.assign(state_shapes.size(), std::vector<float>());
    for (size_t i = 0; i < stream_states.size(); ++i)
        stream_states[i].assign((size_t)state_shapes[i][0] * state_shapes[i][1] * state_shapes[i][2], 0.f);

    auto emit_patch_dec = [&](const std::vector<float>& x) -> bool {
        std::vector<float> lat2((size_t)LATENT * PATCH, 0.f);   // [1,64,2]
        for (int c = 0; c < LATENT; ++c)
            for (int t = 0; t < PATCH; ++t)
                lat2[(size_t)c * PATCH + t] = x[(size_t)t * LATENT + c];
        if (!dec_stream.set("latent", lat2)) return false;
        for (size_t i = 0; i < stream_states.size(); ++i)
            if (!dec_stream.set("s" + std::to_string(i), stream_states[i])) return false;
        if (!dec_stream.run()) return false;
        std::vector<float> pcm = dec_stream.get("wav", (size_t)PATCH * HOP);
        if (pcm.empty()) return false;
        for (size_t i = 0; i < stream_states.size(); ++i) {
            auto o = dec_stream.get("so" + std::to_string(i),
                                    (size_t)state_shapes[i][0] * state_shapes[i][1] * state_shapes[i][2]);
            if (o.empty()) return false;
            stream_states[i].swap(o);
        }
        ++chunks;
        if (ttft < 0) { ttft = ms(t_start, now()); flush_ref_cache(); }
        if (stream) {
            if (!writer.write(pcm.data(), pcm.size())) return false;
        } else {
            streamed.insert(streamed.end(), pcm.begin(), pcm.end());
        }
        return true;
    };

    auto emit = [&](int upto) -> bool {
        std::vector<float> pcm;
        if (!decode_window(emitted_, upto, pcm)) return false;
        emitted_ = upto;
        ++chunks;
        if (ttft < 0) { ttft = ms(t_start, now()); flush_ref_cache(); }
        if (stream) {
            if (!writer.write(pcm.data(), pcm.size())) return false;
        } else {
            streamed.insert(streamed.end(), pcm.begin(), pcm.end());
        }
        return true;
    };
    for (int step = 0; step < max_new; ++step) {
        const bool stop_now = stop.size() >= 2 && (stop[0] < stop[1]);
        std::vector<float> x((size_t)PATCH * LATENT);
        for (auto& v : x) v = nd(gen);
        auto td0 = now();
        for (int k = 0; k < 4; ++k) {
            const float t = 0.25f * k;
            if (!M.dit.set("x", x) || !M.dit.set("z", hidden) || !M.dit.set("cond", cond) ||
                !M.dit.set("speaker", spk) || !M.dit.set("cfg_strength", &cfg_strength, 1) ||
                !M.dit.set("t", &t, 1) || !M.dit.set("dt", std::vector<float>{0.25f}) ||
                !M.dit.run())
                return 10;
            std::vector<float> v = M.dit.get("velocity", (size_t)PATCH * LATENT);
            if (v.empty()) return 10;
            for (size_t i = 0; i < x.size(); ++i) x[i] += v[i] * 0.25f;
        }
        t_dit += ms(td0, now());
        for (int c = 0; c < PATCH; ++c) {
            std::vector<float> lat((size_t)LATENT);
            for (int j = 0; j < LATENT; ++j) lat[j] = x[(size_t)c * LATENT + j] / A.scale - A.bias;
            lat_all.insert(lat_all.end(), lat.begin(), lat.end());
        }
        if (t_first_lat < 0) t_first_lat = ms(t_start, now());
        ++steps;

        if (stream && has_stream_dec) {
            if (!emit_patch_dec(x)) return 14;
        }
        if (stop_now) {
            if (stream && !has_stream_dec && emitted_ < (int)(lat_all.size() / LATENT))
                if (!emit((int)(lat_all.size() / LATENT))) return 14;
            break;
        }
        cond = x;

        std::vector<float> patch = x;
        if (!M.loc.set("patches", patch) || !M.loc.run()) return 11;
        std::vector<float> emb = M.loc.get("embeds", HID);
        if (emb.empty()) return 11;

        mask[pos] = 0.f;
        std::vector<float> cos_t, sin_t;
        run_rope(pos, cos_t, sin_t);
        auto td1 = now();
        if (!M.dec.set("embed", emb) || !M.dec.set("mask_add", mask) || !M.dec.set("cos", cos_t) ||
            !M.dec.set("sin", sin_t))
            return 12;
        for (int i = 0; i < 7; ++i) {
            if (!M.dec.set("pk" + std::to_string(i), kv[2 * i]) ||
                !M.dec.set("pv" + std::to_string(i), kv[2 * i + 1]))
                return 12;
        }
        if (!M.dec.run()) return 12;
        hidden = M.dec.get("hidden", HID);
        stop = M.dec.get("stop", 2);
        if (hidden.empty() || stop.size() < 2) return 12;
        for (int i = 0; i < 7; ++i) {
            auto k = M.dec.get("k" + std::to_string(i), (size_t)8 * 128);
            auto v = M.dec.get("v" + std::to_string(i), (size_t)8 * 128);
            if (k.empty() || v.empty()) return 12;
            for (int h = 0; h < 8; ++h) {
                std::memcpy(&kv[2 * i][(size_t)h * KV * 128 + (size_t)pos * 128],
                            &k[(size_t)h * 128], 128 * sizeof(float));
                std::memcpy(&kv[2 * i + 1][(size_t)h * KV * 128 + (size_t)pos * 128],
                            &v[(size_t)h * 128], 128 * sizeof(float));
            }
        }
        t_dec += ms(td1, now());
        ++pos;

        if (stream && !has_stream_dec) {
            const int total = (int)(lat_all.size() / LATENT);
            const int need = (emitted_ == 0) ? first_chunk : chunk;
            if (total - emitted_ >= need)
                if (!emit(total)) return 14;
        }
        if (pos >= KV - 1) break;
    }
    t5 = now();
    const int total_lat = (int)(lat_all.size() / LATENT);
    if (stream) {
        if (!has_stream_dec && emitted_ < total_lat)
            if (!emit(total_lat)) return 14;
    } else if (total_lat > 0) {
        if (total_lat > 256) {
            std::fprintf(stderr, "audio too long (%d latents > 256)\n", total_lat);
            return 13;
        }
        const int bucket = total_lat <= win_len ? win_len : (total_lat <= 128 ? 128 : 256);
        std::vector<float> vae_lat((size_t)LATENT * bucket, 0.f);
        for (int i = 0; i < total_lat; ++i)
            for (int c = 0; c < LATENT; ++c)
                vae_lat[(size_t)c * bucket + i] = lat_all[(size_t)i * LATENT + c];
        cutetts::AxModel& dec = (bucket == win_len) ? dec_win
                               : (bucket == 128 ? M.dec128 : M.dec256);
        if (!dec.set("latent", vae_lat) || !dec.run()) return 14;
        std::vector<float> wav_seg = dec.get("wav", (size_t)bucket * HOP);
        if (wav_seg.empty()) return 14;
        wav_seg.resize((size_t)total_lat * HOP);
        streamed.insert(streamed.end(), wav_seg.begin(), wav_seg.end());
    }
    offline_pcm.insert(offline_pcm.end(), streamed.begin(), streamed.end());
    t_dit_sum += t_dit;
    t_dec_sum += t_dec;
    steps_sum += steps;
    chunks_sum += chunks;
    total_lat_sum += total_lat;
    }  // end of per-sentence loop

    flush_ref_cache();
    if (stream) {
        if (!writer.close()) return 15;
    } else if (!cutetts::write_wav(out_path, offline_pcm, SR)) {
        return 15;
    }
    const size_t samples = (size_t)total_lat_sum * HOP;
    auto t6 = now();

    const double total_ms = ms(t_start, t6);
    const double dur = double(samples) / SR;
    std::printf("%s: audio %.2fs, TTFT %.2fs (first latent), TTFA %.2fs (first audio), "
                "total %.2fs, RTF %.3f, %d patches, %d chunks, %zu segments\n",
                stream ? "streaming" : "offline", dur,
                (t_first_lat < 0 ? total_ms : t_first_lat) / 1000.0,
                (ttft < 0 ? total_ms : ttft) / 1000.0,
                total_ms / 1000.0, total_ms / 1000.0 / dur, steps_sum, chunks_sum,
                segments.size());
    std::printf("  ref %s  vae_enc %.0f ms  speaker %.0f ms  prompt %.0f ms  prefill %.0f ms  "
                "ar %.0f ms (dit %.0f, lm_dec %.0f)  vae_dec %.0f ms\n",
                ref_cached ? "cached" : "encoded",
                ms(t0, t1), ms(t1, t2), ms(t2, t3), ms(t3, t4), ms(t4, t5), t_dit_sum, t_dec_sum,
                ms(t5, t6));
    if (std::getenv("CUTETTS_PROFILE") && t_cache_flush > 0)
        std::fprintf(stderr, "    [host] ref cache write (after first packet) %.0f ms\n", t_cache_flush);
    std::printf("saved %s\n", out_path.c_str());
    return 0;
}
